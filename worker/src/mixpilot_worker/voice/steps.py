# Шаги, где человек поёт — их фрагменты ценнее для каверов.
SINGING_KINDS = {"melody", "range", "sustain", "vowels"}

TOTAL_CLIPS = sum(len(s["prompts"]) for s in STEPS if s["kind"] != "noise")


def get_step(step_id: int) -> dict | None:
    return next((s for s in STEPS if s["id"] == step_id), None)


def estimate_minutes() -> int:
    """Сколько примерно займёт запись — показываем честно заранее."""
    seconds = sum(len(s["prompts"]) * s["seconds"] * 2 for s in STEPS)  # ×2 на паузы и перезаписи
    return max(1, round(seconds / 60))
